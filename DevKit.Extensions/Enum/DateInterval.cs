namespace DevKit.Extensions.Enum;

/// <summary>Especifica las unidades de tiempo disponibles para cálculos de diferencia de fechas.</summary>
public enum DateInterval
{
    /// <summary>Representa días.</summary>
    Day,
    /// <summary>Representa meses.</summary>
    Month,
    /// <summary>Representa años.</summary>
    Year,
    /// <summary>Representa horas.</summary>
    Hour,
    /// <summary>Representa minutos.</summary>
    Minute,
    /// <summary>Representa segundos.</summary>
    Second
}